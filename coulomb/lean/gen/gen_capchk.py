#!/usr/bin/env python3
"""Row-wise kernel checks of `checkMeta` for a facially reduced cap certificate (`TCertN`, NBlk.lean).

A single `decide` of `TBlkN.okN` for the 84x82 cap blocks exceeds ~10 GB in the kernel (in-kernel N·B'·Nᵀ).
For every SOS block this writes CoulN7/<Name>/Chk<SX><r>.lean with
  * `<blk>_E`  : the stored `entMat nb.inner` (packed, `unpackM`),
  * one `decide` per row of `entMat nb.inner = <blk>_E` and of `toTBlk.B.Δ = N·E·Nᵀ` (rows),
  * the assembled `<blk>_ok : <blk>.okN = true` (`TBlkN.okN_of_parts`, `NBlk.eq_of_getD_rows`, `NBlk.expandΔ_eq`),
and CoulN7/<Name>/ChkMeta.lean (`checkMetaF` by `decide`, `checkMeta` by `TCertN.checkMeta_of_parts`).
Usage: gen_capchk.py <Name>     (reads the Data*.lean of CoulN7/<Name>, written by emit_tcert.py --tcertn)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import emit_tcert as et  # noqa: E402


def padd(p, q):
    out = [a + b for a, b in zip(p, q)]
    return out + (p[len(q):] if len(p) > len(q) else q[len(p):])


def mat_add(A, B):
    out = [padd(a, b) for a, b in zip(A, B)]
    return out + (A[len(B):] if len(A) > len(B) else B[len(A):])


def ent_mat(b):
    """NBlk.entMat, list-exact: matAdd (ldl d l) Δ."""
    acc = []
    for dq, lq in reversed(list(zip(b.d, b.l))):
        x = [dq * v for v in lq]
        acc = mat_add([[a * v for v in lq] for a in x], acc)
    return mat_add(acc, b.D)


def dot(x, y):
    return sum(a * b for a, b in zip(x, y))


def vec_mat(x, M):
    acc = []
    for a, row in reversed(list(zip(x, M))):
        acc = padd([a * v for v in row], acc)
    return acc


def match_rows(n, name):
    """`match a, ha with | 0, _ => name0 | … | _ + n, h => absurd h (by omega)`."""
    cases = "".join(f"\n      | {i}, _ => {name}{i}" for i in range(n))
    return f"match a, ha with{cases}\n      | _ + {n}, h => absurd h (by omega)"


def block_module(nm, sn, r, s, hdr):
    x = f"{nm}_{sn}{r}"
    nb = s.nb
    b = nb.inner()
    E = ent_mat(b)
    m = len(s.z)
    X = [[dot(vec_mat(row, E), rb) for rb in nb.N] for row in nb.N]
    assert X == s.nb.expandD(m), (sn, r, "row formula differs from expandD")
    BE = et.width([v for row in E for v in row])
    cols = len(E[0]) if E else 0
    assert all(len(row) == cols for row in E)
    xE = et.packM_lean(BE, cols, E)
    assert et.unpackM(BE, cols, len(E), xE) == E
    nE, nX = len(E), len(nb.N)
    L = [f"/-- `entMat` of the reduced block of `{x}` ({nE} × {cols}, {BE}-bit fields). -/\n"
         f"def {x}_E : List (List ℤ) := unpackM {BE} {cols} {nE}\n  0x{xE:x}\n\n"
         f"/-- `N · E · Nᵀ` by rows. -/\n"
         f"def {x}_X : List (List ℤ) :=\n  {x}_nb.N.map (fun row => {x}_nb.N.map fun rb => NBlk.dot (NBlk.vecMat row {x}_E) rb)\n\n"
         f"theorem {x}_ok1 : {x}.nb.okN = true := by decide +kernel\n"
         f"theorem {x}_ok2 : {x}.nb.N.length = {x}.m := by decide +kernel\n"
         f"theorem {x}_ok3 : {x}.toTBlk.B.d.all (fun v => decide (v = 0)) = true := by decide +kernel\n"
         f"theorem {x}_El : (NBlk.entMat {x}_nb.inner).length = {nE} := by decide +kernel\n"
         f"theorem {x}_Er : {x}_E.length = {nE} := by decide +kernel\n"
         f"theorem {x}_Dl : {x}.toTBlk.B.Δ.length = {nX} := by decide +kernel\n"
         f"theorem {x}_Xr : {x}_X.length = {nX} := by decide +kernel\n\n"]
    for i in range(nE):
        L.append(f"theorem {x}_E{i} : (NBlk.entMat {x}_nb.inner).getD {i} [] = {x}_E.getD {i} [] := by decide +kernel\n")
    L.append("\n")
    for a in range(nX):
        L.append(f"theorem {x}_D{a} : {x}.toTBlk.B.Δ.getD {a} [] = {x}_X.getD {a} [] := by decide +kernel\n")
    L.append(f"\ntheorem {x}_hE : NBlk.entMat {x}_nb.inner = {x}_E :=\n"
             f"  NBlk.eq_of_getD_rows ({x}_El.trans {x}_Er.symm) fun a ha => by\n"
             f"    rw [{x}_El] at ha\n    exact {match_rows(nE, x + '_E')}\n\n"
             f"theorem {x}_hD : {x}.toTBlk.B.Δ = {x}_X :=\n"
             f"  NBlk.eq_of_getD_rows ({x}_Dl.trans {x}_Xr.symm) fun a ha => by\n"
             f"    rw [{x}_Dl] at ha\n    exact {match_rows(nX, x + '_D')}\n\n"
             f"theorem {x}_ok : {x}.okN = true :=\n"
             f"  TBlkN.okN_of_parts {x}_ok1 {x}_ok2 {x}_ok3\n"
             f"    ({x}_hD.trans (NBlk.expandΔ_eq {x}_nb {x}_hE).symm)\n")
    return "".join(L), (m, nE, BE)


def main(name):
    outdir = os.path.join(et.LEANROOT, "CoulN7", name)
    tcn, _ = et.parse_n(outdir, name)
    nm = "tc_" + name.lower()
    sec = f"CoulN7_{name}_tc"
    mod = f"CoulN7.{name}"
    split = os.path.exists(os.path.join(outdir, "DataA.lean"))

    def hdr(imports, what):
        return ("".join(f"import {i}\n" for i in imports)
                + f"/-! {what}\n    Generated by `numerics/n7_interval/lean/gen/gen_capchk.py {name}` from the `TCertN` data of {name}.\n"
                + "    Row-wise kernel checks (one `decide` per row; a whole-block `decide` exceeds ~10 GB).  Regenerate; do not edit. -/\n\n")

    body = lambda s: f"open Real\n\nsection {sec}\n" + et.OPENS + s + f"\nend CoulN7\nend {sec}\n"
    mods, parts = [], []
    for sn in ("SA", "SB", "SG"):
        names = []
        for r, s in enumerate(getattr(tcn, sn)):
            txt, info = block_module(nm, sn, r, s, hdr)
            fn = f"Chk{sn}{r}"
            with open(os.path.join(outdir, fn + ".lean"), "w") as fh:
                fh.write(hdr([f"{mod}.Data{sn[1]}" if split else f"{mod}.Data"],
                             f"Kernel check `TBlkN.okN` of the SOS block `{sn}{r}` of {name} (m, r, E bits = {info}).")
                         + body(txt))
            mods.append(fn)
            names.append(f"{nm}_{sn}{r}")
            print(fn, info, flush=True)
        parts.append(names)
    lst = lambda xs: "[" + ", ".join(xs) + "]"
    simp_ok = lambda names: ("by\n    show List.all " + lst(names) + " TBlkN.okN = true\n"
                             "    simp only [List.all_cons, List.all_nil, Bool.and_true, "
                             + ", ".join(f"{x}_ok" for x in names) + "]")
    with open(os.path.join(outdir, "ChkMeta.lean"), "w") as fh:
        fh.write(hdr([f"{mod}.Data"] + [f"{mod}.{f}" for f in mods],
                     f"Kernel check `checkMeta` of {name}, assembled from `checkMetaF` and the per-block checks.")
                 + body(f"theorem {nm}_metaF : {nm}.checkMetaF = true := by decide +kernel\n\n"
                        f"theorem {nm}_meta : {nm}.checkMeta = true :=\n  {nm}.checkMeta_of_parts {nm}_metaF\n"
                        + "".join(f"    ({simp_ok(n)})\n" for n in parts)))
    print("ChkMeta", len(mods), "block modules")


if __name__ == "__main__":
    main(sys.argv[1])

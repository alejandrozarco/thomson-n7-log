#!/usr/bin/env python3
"""Spec modules of the Coulomb port: CoulN7/<Slab>/Spec.lean (SlabSpec φ₁), CoulN7/Case1/Claim.lean (Case1Claim φ₁),
CoulN7/Cap/Spec.lean (CapSpec φ₁ (1/165000) (-99/100)).

usage: python3 gen_spec1.py [slabs|case1|cap ...]   (default: slabs case1 cap)
Reads the emitted certificate data (emit_tcert.py parse / parse_n, cert3_parse) and checks the numeric side
conditions exactly (E(P) upper bound U of CoulN7.Basic vs ef).
"""
import os
import re
import sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import emit_tcert as et  # noqa: E402

MB = et.LEANROOT
EPU = Fr(14452977414221342935044494, 10 ** 24)
SLABS = ["S9998", "S9896", "S9694", "S9493", "S9390"]
DMIN = 100 * 2 ** 24


def q(x):
    x = Fr(x)
    return f"({x.numerator} / {x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"


def slab(name):
    tc, _ = et.parse(os.path.join(MB, "CoulN7", name), name)
    nm = "tc_" + name.lower()
    M = f"CoulN7.Minor.M{name}"
    lo, hi = Fr(tc.an, tc.ad), Fr(tc.bn, tc.bd)
    ef = Fr(tc.e, tc.Lam)
    assert EPU < ef, (name, float(ef - EPU))
    s = f"""import CoulN7.{name}.ChkMeta
import CoulN7.{name}.ChkA
import CoulN7.{name}.ChkB
import CoulN7.{name}.ChkG
import CoulN7.Bridge
import CoulN7.Minor.{name}
/-! Slab {name}: `ThomsonGen.SlabSpec φ₁ {q(lo)} {q(hi)}` (Coulomb) from the checked packed certificate `{nm}` and
the minorants of `{M}` (identified through `scaledEq`).
Generated by `numerics/n7_interval/lean/gen/gen_spec1.py`; do not edit. -/

open Real
namespace CoulN7
namespace {name}
open ThomsonN7 ThomsonN7.Cert ThomsonGen

theorem e_eq : {nm}.e = {tc.e} := rfl
theorem lam_eq : {nm}.Lam = {tc.Lam} := rfl
theorem an_eq : {nm}.an = {tc.an} := rfl
theorem ad_eq : {nm}.ad = {tc.ad} := rfl
theorem bn_eq : {nm}.bn = {tc.bn} := rfl
theorem bd_eq : {nm}.bd = {tc.bd} := rfl
theorem lam_pos : 0 < {nm}.Lam := by rw [lam_eq]; norm_num
theorem alo_eq : {nm}.alo = {q(lo)} := by
  unfold TCert.alo; rw [an_eq, ad_eq]; norm_num
theorem ahi_eq : {nm}.ahi = {q(hi)} := by
  unfold TCert.ahi; rw [bn_eq, bd_eq]; norm_num
/-- `E(P) < ef` (margin {float(ef - EPU):.3e}). -/
theorem ef_gt : pairEnergy ThomsonN7.Base.phi pentBipyramid < {nm}.ef := by
  refine lt_of_le_of_lt pairEnergy_pent_le ?_
  unfold TCert.ef; rw [e_eq, lam_eq]; norm_num
theorem eA : scaledEq {M}.HAd {nm}.HA {nm}.Lam {M}.HA = true := by decide +kernel
theorem eB : scaledEq {M}.HBd {nm}.HB {nm}.Lam {M}.HB = true := by decide +kernel
theorem eC : scaledEq {M}.HCd {nm}.HC {nm}.Lam {M}.HC = true := by decide +kernel

/-- **Slab {name}.** -/
theorem spec : SlabSpec ThomsonN7.Base.phi {q(lo)} {q(hi)} :=
  slabSpec_of_minor {nm} {nm}_meta {nm}_A {nm}_B {nm}_G alo_eq ahi_eq ef_gt lam_pos
    (by decide) (by decide) (by decide) eA eB eC
    (fun t h1 h2 => {M}.HA_le t h1 h2) (fun t h1 h2 => {M}.HB_le t h1 h2)
    (fun t h1 h2 => {M}.HC_le t h1 h2)

end {name}
end CoulN7
"""
    open(os.path.join(MB, "CoulN7", name, "Spec.lean"), "w").write(s)
    print(name, "ef - U =", float(ef - EPU))


def case1():
    src = open(os.path.join(MB, "CoulN7", "Case1", "Data.lean")).read()

    def grab(field):
        m = re.search(rf"\b{field}\s*:=\s*(-?\d+)", src)
        return int(m.group(1)) if m else None
    import cert3_parse as cp
    cf, _ = cp.parse_data(open(os.path.join(MB, "CoulN7", "Case1", "Data.lean")).read())
    Lam, eps = cf.Lam, cf.eps
    an, ad = cf.an, cf.ad
    assert Fr(an, ad) == Fr(-9, 10)
    ev = Fr(eps, Lam)
    assert EPU < ev, float(ev - EPU)
    M = "CoulN7.Minor.MCase1"
    s = f"""import CoulN7.Case1.Check
import CoulN7.Bridge
import CoulN7.Minor.Case1
/-! Coulomb kernel, Case 1 claim: `ThomsonGen.Case1Claim φ₁` from the checked cut certificate
(`CoulN7.Case1Data.cf`, `r2c1_cf_ok`) and the minorant `H ≤ φ₁` on `[-9/10, 1)` (`{M}.HH_le`, the same rational
polynomial over another denominator: `scaledEq`).  Margin `η = eps/Λ − U ≈ {float(ev - EPU):.3e}`, `U ≥ E(P)`
(`pairEnergy_pent_le`).  Generated by `numerics/n7_interval/lean/gen/gen_spec1.py`; do not edit. -/

open Real
namespace CoulN7
namespace Case1
open ThomsonN7 ThomsonN7.Cert ThomsonN7.Cert.Cert3 ThomsonGen

theorem lam_eq : CoulN7.Case1Data.cf.Lam = {Lam} := rfl
theorem eps_eq : CoulN7.Case1Data.cf.eps = {eps} := rfl
theorem an_eq : CoulN7.Case1Data.cf.an = {an} := rfl
theorem ad_eq : CoulN7.Case1Data.cf.ad = {ad} := rfl
theorem lam_pos : 0 < CoulN7.Case1Data.cf.Lam := by rw [lam_eq]; norm_num

theorem h_scaled : scaledEq {M}.HHd CoulN7.Case1Data.cf.h CoulN7.Case1Data.cf.Lam {M}.HH = true := by
  decide +kernel

/-- **Case 1 (Coulomb kernel).** -/
theorem claim : Case1Claim ThomsonN7.Base.phi := by
  have hEP := pairEnergy_pent_le
  have hq : ((CoulN7.Case1Data.cf.eps : ℤ) : ℝ) / ((CoulN7.Case1Data.cf.Lam : ℕ) : ℝ) =
      ({eps} : ℝ) / {Lam} := by
    rw [eps_eq, lam_eq]; push_cast; ring
  have hm : (14452977414221342935044494 : ℝ) / 10 ^ 24 < ({eps} : ℝ) / {Lam} := by norm_num
  have han : ((CoulN7.Case1Data.cf.an : ℤ) : ℝ) / (CoulN7.Case1Data.cf.ad : ℝ) = -9 / 10 := by
    rw [an_eq, ad_eq]; norm_num
  refine case1Claim_of_cert3 CoulN7.Case1Data.cf r2c1_cf_ok rfl han
    (η := ({eps} : ℝ) / {Lam} - (14452977414221342935044494 : ℝ) / 10 ^ 24)
    (by linarith) (by rw [hq]; linarith) lam_pos (by decide) h_scaled ?_
  intro t h1 h2
  exact {M}.HH_le t h1 h2

end Case1
end CoulN7
"""
    open(os.path.join(MB, "CoulN7", "Case1", "Claim.lean"), "w").write(s)
    print("Case1 eps/Lam - U =", float(ev - EPU))


def cap():
    tcn, _ = et.parse_n(os.path.join(MB, "CoulN7", "Cap"), "Cap")
    tc = tcn.toTCert() if hasattr(tcn, "toTCert") else tcn
    e, Lam = tc.e, tc.Lam
    ef = Fr(e, Lam)
    assert EPU <= ef + Fr(1, 10 ** 16), float(EPU - ef)
    assert Fr(tc.an, tc.ad) == -1 and Fr(tc.bn, tc.bd) == Fr(-99, 100)
    M = "CoulN7.Minor.MCap"
    s = f"""import CoulN7.Cap.ChkMeta
import CoulN7.Cap.ChkA
import CoulN7.Cap.ChkB
import CoulN7.Cap.ChkG
import CoulN7.Bridge
import CoulN7.Minor.Cap
/-! Cap: `ThomsonGen.CapSpec φ₁ (1/165000) (-99/100)` (Coulomb) from the checked facially reduced certificate
`tc_cap` (`Cert.TCertN`, re-rounded, not sharp: E(P) − ef ≤ U − ef = {float(EPU - ef):.4e} ≤ δ = 10⁻¹⁶) and the
coercive minorants of `{M}` (identified through `scaledEq`).  Coercivity windows: half-width
8000/(100·2²⁴) = 4.77·10⁻⁶ < τ₀ = 1/165000 around −1, 0 and grid roundings of c₁, c₂.
Generated by `numerics/n7_interval/lean/gen/gen_spec1.py`; do not edit. -/

open Real
namespace CoulN7
namespace Cap
open ThomsonN7 ThomsonN7.Cert ThomsonGen
open LogLean.Minor (peval)

theorem e_eq : tc_cap.toTCert.e = {e} := rfl
theorem lam_eq : tc_cap.toTCert.Lam = {Lam} := rfl
theorem an_eq : tc_cap.toTCert.an = -1 := rfl
theorem ad_eq : tc_cap.toTCert.ad = 1 := rfl
theorem bn_eq : tc_cap.toTCert.bn = -99 := rfl
theorem bd_eq : tc_cap.toTCert.bd = 100 := rfl
theorem lam_pos : 0 < tc_cap.toTCert.Lam := by rw [lam_eq]; norm_num
theorem alo_eq : tc_cap.toTCert.alo = -1 := by
  unfold TCert.alo; rw [an_eq, ad_eq]; norm_num
theorem ahi_eq : tc_cap.toTCert.ahi = (-99 / 100 : ℝ) := by
  unfold TCert.ahi; rw [bn_eq, bd_eq]; norm_num
/-- `E(P) ≤ ef + δ`, `δ = 10⁻¹⁶`. -/
theorem ef_ge : pairEnergy ThomsonN7.Base.phi pentBipyramid ≤ tc_cap.toTCert.ef + 1 / 10 ^ 16 := by
  refine pairEnergy_pent_le.trans ?_
  unfold TCert.ef; rw [e_eq, lam_eq]; norm_num
theorem eA : scaledEq {M}.HAd tc_cap.toTCert.HA tc_cap.toTCert.Lam {M}.HA = true := by decide +kernel
theorem eB : scaledEq {M}.HBd tc_cap.toTCert.HB tc_cap.toTCert.Lam {M}.HB = true := by decide +kernel
theorem eC : scaledEq {M}.HCd tc_cap.toTCert.HC tc_cap.toTCert.Lam {M}.HC = true := by decide +kernel

theorem capA (t : ℝ) (h1 : -1 ≤ t) (h2 : t ≤ (-99 / 100 : ℝ)) :
    peval {M}.HA t / {M}.HAd ≤ ThomsonN7.Base.phi t ∧
    (ThomsonN7.Base.phi t - peval {M}.HA t / {M}.HAd ≤ 1 / 10 ^ 16 → |t + 1| ≤ 1 / 165000) := by
  refine ⟨{M}.HA_le t h1 h2, fun h => ?_⟩
  have w := {M}.HA_coerc t h1 h2 h
  rw [{M}.D_eq] at w
  push_cast at w
  rw [abs_le]
  constructor <;> linarith [w.1, w.2]

theorem capB (t : ℝ) (h1 : -1 ≤ t) (h2 : t < 1) :
    peval {M}.HB t / {M}.HBd ≤ ThomsonN7.Base.phi t ∧
    (ThomsonN7.Base.phi t - peval {M}.HB t / {M}.HBd ≤ 1 / 10 ^ 16 → |t| ≤ 1 / 165000) := by
  refine ⟨{M}.HB_le t h1 h2, fun h => ?_⟩
  have w := {M}.HB_coerc t h1 h2 h
  rw [{M}.D_eq] at w
  push_cast at w
  rw [abs_le]
  constructor <;> linarith [w.1, w.2]

theorem capC (t : ℝ) (h1 : -1 ≤ t) (h2 : t < 1) :
    peval {M}.HC t / {M}.HCd ≤ ThomsonN7.Base.phi t ∧
    (ThomsonN7.Base.phi t - peval {M}.HC t / {M}.HCd ≤ 1 / 10 ^ 16 →
      |t - (-1 + √5) / 4| ≤ 1 / 165000 ∨ |t - (-1 - √5) / 4| ≤ 1 / 165000) := by
  refine ⟨{M}.HC_le t h1 h2, fun h => ?_⟩
  have w := {M}.HC_coerc t h1 h2 h
  rw [{M}.D_eq] at w
  push_cast at w
  obtain ⟨l5, u5⟩ := sqrt5_enc
  rcases w with w | w
  · right
    rw [abs_le]
    constructor <;> linarith [w.1, w.2]
  · left
    rw [abs_le]
    constructor <;> linarith [w.1, w.2]

/-- **The Coulomb cap.** -/
theorem spec : CapSpec ThomsonN7.Base.phi (1 / 165000) (-99 / 100 : ℝ) :=
  capSpec_of_minorN tc_cap tc_cap_meta tc_cap_A tc_cap_B tc_cap_G alo_eq ahi_eq ef_ge lam_pos
    (by decide) (by decide) (by decide) eA eB eC capA capB capC

end Cap
end CoulN7
"""
    open(os.path.join(MB, "CoulN7", "Cap", "Spec.lean"), "w").write(s)
    print("Cap U - ef =", float(EPU - ef))


if __name__ == "__main__":
    what = sys.argv[1:] or ["slabs", "case1", "cap"]
    if "slabs" in what:
        for n in SLABS:
            slab(n)
    for n in what:
        if n in SLABS:
            slab(n)
    if "case1" in what:
        case1()
    if "cap" in what:
        cap()

#!/usr/bin/env python3
"""Emit CoulN7/Minor/<Cell>.lean: exact minorant (and, for the cap, coercivity) checks for the Coulomb kernel.

usage: python3 gen_minor1.py [cells...]      (default: all seven; cells: Case1 S9998 S9896 S9694 S9493 S9390 Cap)

Every Lean Bool check (`gapPoly … = q`, `nnChainOK q D ps lo hi`) is simulated here with the Lean list semantics
(minor1.py) before the file is written.  Grid: D = 100·2^24 (−99/100, −9/10 etc. are grid points).
Cap coercivity: δ = 10⁻¹⁶, the chains certify H + 2δ ≤ φ₁ outside windows of half-width W/D (W = 8000,
W/D = 4.77e−6 < τ₀ = 1/165000), centred at −1 (one-sided), 0, and grid roundings of c₁, c₂.
"""
import hashlib
import json
import os
import sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from minor1 import gapPoly, shiftN, nnChainOK, build_chain, int_poly  # noqa: E402

from mpmath import mp, sqrt, nint  # noqa: E402

mp.dps = 50
MB = os.environ.get("COULN7_LEAN", os.path.join(os.path.expanduser("~"), "claude_projects", "thomson-n7-log-macbuild", "lean"))
NUM = os.environ.get("COULN7_NUMERICS", os.path.normpath(os.path.join(HERE, "..", "..")))   # numerics/n7_interval
D = 100 * 2 ** 24
W = 8000
DELTA_M = 10 ** 16
CELLS = {
    "Case1": ("cells1/certs/cert_case1_coulomb_D10.json", Fr(-9, 10), None),
    "S9998": ("cells1/certs/cert_slab_99_98_coulomb_D10.json", Fr(-99, 100), Fr(-49, 50)),
    "S9896": ("cells1/certs/cert_slab_98_96_coulomb_D10.json", Fr(-49, 50), Fr(-24, 25)),
    "S9694": ("cells1/certs/cert_slab_96_94_coulomb_D12.json", Fr(-24, 25), Fr(-47, 50)),
    "S9493": ("cells1/certs/cert_slab_94_93_coulomb_D12.json", Fr(-47, 50), Fr(-93, 100)),
    "S9390": ("cells1/certs/cert_slab_93_90_coulomb_D12.json", Fr(-93, 100), Fr(-9, 10)),
    "Cap": ("cap1/cert_cap_coulomb_D12_short.json", Fr(-1), Fr(-99, 100)),
}


def gi(x):
    v = x * D
    assert v.denominator == 1
    return int(v)


def lst(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def plst(ps):
    return "[" + ", ".join(f"({a}, {b})" for a, b in ps) + "]"


def chain(q, lo, hi, tag):
    ps, fail = build_chain(q, D, lo, hi)
    assert ps is not None, (tag, "chain failed at", fail / D)
    assert nnChainOK(q, D, ps, lo, hi), tag
    return ps


def rl(x):
    """real literal for a Fraction"""
    x = Fr(x)
    return f"({x.numerator} : ℝ)" if x.denominator == 1 else f"(({x.numerator} : ℝ) / {x.denominator})"


def emit(cell):
    path, lo, hi = CELLS[cell]
    src = os.path.join(NUM, path)
    sha = hashlib.sha256(open(src, "rb").read()).hexdigest()
    J = json.load(open(src))
    H = {"H": J["H"]} if cell == "Case1" else J["H"]
    out = []
    out.append("import CoulN7.MinorCore\n")
    out.append(f"/-! Coulomb minorants of the cell `{cell}`: `H ≤ (√(2-2t))⁻¹` on the class ranges"
               + (", and coercivity (`φ₁ - H ≥ 2·10⁻¹⁶` outside the contact windows)" if cell == "Cap" else "")
               + f".\n    Generated by `numerics/n7_interval/lean/gen/gen_minor1.py` from `numerics/n7_interval/{path}`\n"
               f"    (sha256 {sha[:16]}…).  Do not edit; regenerate. -/\n")
    out.append(f"namespace CoulN7.Minor.M{cell}\n\nopen LogLean.Minor CoulN7.Minor\n")
    out.append("set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n")
    out.append(f"def D : ℕ := {D}\n")
    out.append(f"theorem D_eq : (D : ℝ) = {D} := by norm_num [D]\n")
    stats = {}
    loI = gi(lo)
    windows = {}
    if cell == "Cap":
        c1 = int(nint((sqrt(5) - 1) / 4 * D))
        c2 = int(nint(-(1 + sqrt(5)) / 4 * D))
        windows = {"A": [(-D, -D + W)], "B": [(-W, W)], "C": [(c2 - W, c2 + W), (c1 - W, c1 + W)]}
    for X, coeffs in H.items():
        Hn, Hd = int_poly(coeffs)
        if X == "A":
            hiI = gi(hi) + 1
            rng = f"(h0 : {rl(lo)} ≤ t) (h1 : t ≤ {rl(hi)})"
        else:
            hiI = D
            rng = f"(h0 : {rl(lo)} ≤ t) (h1 : t < 1)"
        q = gapPoly(Hn, Hd)
        ps = chain(q, loI, hiI, (cell, X))
        stats[X] = len(ps)
        out.append(f"/-! ### class {X} -/\n")
        out.append(f"def H{X} : List ℤ := {lst(Hn)}\ndef H{X}d : ℕ := {Hd}\n")
        out.append(f"def q{X} : List ℤ := {lst(q)}\n")
        out.append(f"def ps{X} : List (ℤ × ℤ) := {plst(ps)}\n")
        out.append(f"theorem q{X}_eq : gapPoly H{X} H{X}d = q{X} := by decide +kernel\n")
        out.append(f"theorem chk{X} : nnChainOK q{X} D ps{X} ({loI}) ({hiI}) = true := by decide +kernel\n")
        out.append(
            f"theorem H{X}_le (t : ℝ) {rng} :\n    peval H{X} t / H{X}d ≤ (√(2 - 2 * t))⁻¹ :=\n"
            f"  le_phi_chain H{X} H{X}d D ps{X} ({loI}) ({hiI}) (by decide) (by decide) (by decide)\n"
            f"    (by rw [q{X}_eq]; exact chk{X}) (by rw [D_eq]; push_cast; linarith)\n"
            f"    (by rw [D_eq]; push_cast; linarith)\n")
        if cell == "Cap":
            q2 = gapPoly(shiftN(Hn, Hd, 2, DELTA_M), DELTA_M * Hd)
            segs = []
            l = loI
            for (a, b) in windows[X]:
                if a > l:
                    segs.append((l, a))
                l = b
            if l < hiI:
                segs.append((l, hiI))
            out.append(f"def r{X} : List ℤ := {lst(q2)}\n")
            out.append(f"theorem r{X}_eq : gapPoly (shiftN H{X} H{X}d 2 {DELTA_M}) ({DELTA_M} * H{X}d) = r{X} := by\n"
                       "  decide +kernel\n")
            names = []
            for k, (a, b) in enumerate(segs):
                pk = chain(q2, a, b, (cell, X, "coerc", k))
                stats[f"{X}c{k}"] = len(pk)
                out.append(f"def ps{X}c{k} : List (ℤ × ℤ) := {plst(pk)}\n")
                out.append(f"theorem chk{X}c{k} : nnChainOK r{X} D ps{X}c{k} ({a}) ({b}) = true := by decide +kernel\n")
                out.append(
                    f"theorem gap{X}c{k} (t : ℝ) (h0 : (({a} : ℤ) : ℝ) ≤ D * t) (h1 : (D : ℝ) * t < (({b} : ℤ) : ℝ)) :\n"
                    f"    ((2 : ℤ) : ℝ) / ({DELTA_M} : ℕ) ≤ (√(2 - 2 * t))⁻¹ - peval H{X} t / H{X}d :=\n"
                    f"  shift_le_phi_chain H{X} H{X}d 2 {DELTA_M} D ps{X}c{k} ({a}) ({b}) (by decide) (by decide)\n"
                    f"    (by decide) (by decide) (by rw [r{X}_eq]; exact chk{X}c{k}) h0 h1\n")
                names.append((k, a, b))
            # coercivity statement: φ₁ - H ≤ δ ⇒ t in one of the windows (integer form)
            iv = lambda a, b: f"(({a} : ℤ) : ℝ) ≤ D * t ∧ (D : ℝ) * t < (({b} : ℤ) : ℝ)"
            wins = windows[X]
            win = " ∨ ".join(iv(a, b) for a, b in wins)
            ivs = sorted([(a, b, "w", j) for j, (a, b) in enumerate(wins)] + [(a, b, "s", k) for k, a, b in names])
            assert ivs[0][0] == loI and ivs[-1][1] == hiI and all(ivs[i][1] == ivs[i + 1][0] for i in range(len(ivs) - 1))
            L = [f"theorem H{X}_coerc (t : ℝ) {rng}\n"
                 f"    (h : (√(2 - 2 * t))⁻¹ - peval H{X} t / H{X}d ≤ 1 / 10 ^ 16) :\n    {win} := by\n",
                 f"  have e2 : ((2 : ℤ) : ℝ) / (({DELTA_M} : ℕ) : ℝ) = 2 / 10 ^ 16 := by norm_num\n",
                 f"  have p0 : (({loI} : ℤ) : ℝ) ≤ D * t := by rw [D_eq]; push_cast; linarith\n",
                 f"  have pn : (D : ℝ) * t < (({hiI} : ℤ) : ℝ) := by rw [D_eq]; push_cast; linarith\n"]
            for i, (a, b, kind, j) in enumerate(ivs):
                L.append(f"  by_cases n{i} : {iv(a, b)}\n")
                if kind == "s":
                    L.append(f"  · have g := gap{X}c{j} t n{i}.1 n{i}.2\n    linarith\n")
                else:
                    disj = ["Or.inl", "Or.inr"]
                    if len(wins) == 1:
                        L.append(f"  · exact n{i}\n")
                    elif j == 0:
                        L.append(f"  · exact Or.inl n{i}\n")
                    else:
                        L.append(f"  · exact Or.inr n{i}\n")
                L.append(f"  have p{i + 1} : (({b} : ℤ) : ℝ) ≤ D * t := by\n"
                         f"    by_contra hc\n    exact n{i} ⟨p{i}, lt_of_not_ge hc⟩\n")
            L.append(f"  exact absurd pn (not_lt.2 p{len(ivs)})\n")
            out.append("".join(L))
        out.append("\n")
    out.append(f"end CoulN7.Minor.M{cell}\n")
    fn = os.path.join(MB, "CoulN7", "Minor", f"{cell}.lean")
    os.makedirs(os.path.dirname(fn), exist_ok=True)
    open(fn, "w").write("\n".join(out))
    print(cell, stats, os.path.getsize(fn), "bytes")


if __name__ == "__main__":
    for c in (sys.argv[1:] or list(CELLS)):
        emit(c)

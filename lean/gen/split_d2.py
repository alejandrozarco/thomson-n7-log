"""Split of the degree-4 Bombieri list (old LocalGlobD2 ran away to 17 GB computing `pow (sumsq 16 2 14) 4`).

S⁴ = Σ_c chunk_c · S³ with chunk_c = rows 4c..4c+3 of `sumsq 16 2 14`; S³ and the four products are exported as
literals, each product is one kernel check (≈ 2.2k Kel products + |P_c| for the `eqPoly` negation).
Writes LocalGlobD2 (S3lit, Sok16_1..3), LocalGlobD3a..d (P_c), LocalGlobD4 (S4m, ws4, Sok4m, chunk split).
usage: nice -n 19 python3 lean/gen/split_d2.py
"""
import os
import sp_mirror as M
from export_local_data import poly_lean

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.join(HERE, '..', 'LogLean')
HDR = '''import LogLean.{imp}

/-! # {nm}: {doc} (GENERATED by `lean/gen/split_d2.py`; consequences in LocalGlobal) -/

namespace LocalGlobal
open LocalKel LocalSP LocalBomb LocalGlobData

'''
S = M.sumsq(16, 2, 14)
S3 = M.pw(S, 3)
assert S3 == M.pw(S, 3) and len(S) == 14
CH = [(2 * c, 2 * c + 2) for c in range(7)]   # 4-row chunks: D2-size kernel peaks, 2 rows keep ≈ 5 GB
P = []
for a, b in CH:
    M.reset_ops()
    P.append(M.mul(S[a:b], S3))
    print('chunk', a, b, len(P[-1]), dict(M.OPS))
S4 = M.pw(S, 4)
acc = []
for p in reversed(P):
    acc = M.merge(p, acc) if acc else p
assert M.eq_poly(acc, S4) and acc == S4, 'chunk sum != S^4'


def w(name, imp, doc, body):
    open(os.path.join(LEAN, name + '.lean'), 'w').write(HDR.format(imp=imp, nm=name, doc=doc) + body
                                                          + '\nend LocalGlobal\n')


pf = 'set_option profiler true in\n'
if False: w('LocalGlobD2', 'LocalGlobD', 'the cubic multinomial list as a literal, `Sok` for degrees 1–3',
  f'/-- `(Σ_p w_p²)³` (560 terms) -/\ndef S3lit : Poly :=\n  {poly_lean(S3, "   ")}\n\n'
  '/-- rows `4c … 4c+3` of `Σ_p w_p²` -/\ndef chunkS (c : ℕ) : Poly := ((sumsq 16 2 14).drop (4 * c)).take 4\n\n'
  + pf + 'theorem S3_eq : eqPoly (S16 3) S3lit = true := by decide +kernel\n'
  + ''.join(pf + f'theorem Sok16_{d} : Sok (S16 {d}) = true := by decide +kernel\n' for d in (1, 2, 3)))
SFX = 'abcdefg'
def chk(c):
    return f'(((sumsq 16 2 14).drop {2 * c}).take 2)'
for c, sfx in enumerate(SFX):
    w(f'LocalGlobD3{sfx}', 'LocalGlobD2', f'the product chunk `P{c} = (rows {2*c}, {2*c+1} of Σw²) · S³` ({len(P[c])} terms)',
      f'set_option maxRecDepth 100000 in\ndef P{c} : Poly :=\n  {poly_lean(P[c], "   ")}\n\n'
      + pf + f'theorem P{c}_eq : eqPoly (mul {chk(c)} S3lit) P{c} = true := by decide +kernel\n')
w('LocalGlobD4', '\nimport LogLean.'.join(f'LocalGlobD3{x}' for x in SFX),
  'the quartic multinomial list `S4m = P0 + … + P6`, `wsub` and `Sok` on it',
  '/-- balanced merge tree (≈ 16k monomial comparisons instead of ≈ 27k for the linear chain) -/\n'
  'def S4m : Poly := merge (merge (merge P0 P1) (merge P2 P3)) (merge (merge P4 P5) P6)\n\n'
  'theorem chunks_eq : sumsq 16 2 14 = ' + ' ++ '.join(chk(c) for c in range(7)) + ' := by decide +kernel\n\n'
  + pf + 'theorem ws4 : wsub 4 (constDP G4_0) S4m = true := by decide +kernel\n'
  + pf + 'theorem Sok4m : Sok S4m = true := by decide +kernel\n')
print('sizes', len(S3), [len(p) for p in P], len(S4))

"""Generator of the data modules LocalFrames / LocalPairData / LocalPairsA-C / LocalGlobData (Lemma L').

Reads lean/gen/local_global_out.json (local_global.py).  usage: python3 lean/gen/export_local_data.py [frames pairs glob]
"""
import os, sys, json
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.join(HERE, '..', 'LogLean')
JG = json.load(open(os.path.join(HERE, 'local_global_out.json')))


def q(x):
    x = Fr(x)
    return f'{x.numerator}' if x.denominator == 1 else f'{x.numerator}/{x.denominator}'


def kel(c):
    return '⟨' + ', '.join(q(v) for v in c) + '⟩'


def poly_lean(p, ind='    '):
    if not p:
        return '[]'
    rows = [f'({m}, {kel(c)})' for m, c in p]
    return '[' + (',\n' + ind).join(rows) + ']'


def kmat(rows):
    return '[' + ',\n   '.join('[' + ', '.join(kel(c) for c in r) + ']' for r in rows) + ']'


PAIRS = [(i, j) for i in range(7) for j in range(i + 1, 7)]
CLSN = {'ring_adj': 0, 'ring_diag': 1, 'pole_ring': 2, 'pole_pole': 3}

FRAMES_HEAD = '''import LogLean.LocalAtom

/-!
# LocalFrames: the bipyramid, its frames and the pair classes over K = ℚ(α) (generated data)

GENERATED by `lean/gen/export_local_data.py frames` from `local_global.py`; do not edit.
`Pk i k`, `E1k i k`, `E2k i k`: coordinates of `Pᵢ` and of the tangent frame `(E1ᵢ, E2ᵢ)` (ring: `e_z`,
`(−sin θ, cos θ, 0)`; poles: `e_x`, `e_y`); `Kd p b`: the five kernel vectors (rotation fields `b = 0,1,2`, `ŝ₁ ŝ₂`).
`clsIdx i j` selects the class data of `LocalAtom` (0 adj, 1 diag, 2 pole–ring, 3 pole–pole); `atA … atRj` are the
six pair atoms as polynomials in the 4 local coordinates `(x_{2i}, x_{2i+1}, x_{2j}, x_{2j+1})`.
The Boolean checks (`frameOK`, `rotOK`, `gramOK`, `pairOK`, `critOK`, `symOK`, `clsOK`) are the exact K-identities
that `LocalGeom` needs; each is proved by `decide +kernel`.
-/

namespace LocalFrames
open LocalKel LocalSP LocalAtom

'''

FRAMES_TAIL = '''
def Pk (i k : ℕ) : Kel := (Pdat.getD i []).getD k Kel.zero
def E1k (i k : ℕ) : Kel := (E1dat.getD i []).getD k Kel.zero
def E2k (i k : ℕ) : Kel := (E2dat.getD i []).getD k Kel.zero
def Kd (p b : ℕ) : Kel := (Kdat.getD p []).getD b Kel.zero
/-- Gram diagonal of the kernel vectors -/
def gram (b : ℕ) : ℚ := [9/2, 9/2, 5, 5/2, 5/2].getD b 0

/-- class of the pair: 0 adj, 1 diag, 2 pole–ring, 3 pole–pole (4 on the diagonal) -/
def clsIdx (i j : ℕ) : ℕ := (clsTab.getD i []).getD j 4
def gof (i j : ℕ) : Kel := match clsIdx i j with | 0 => g_adj | 1 => g_diag | 2 => g_pole | _ => g_pp
def Wof (i j : ℕ) : Kel := match clsIdx i j with | 0 => W_adj | 1 => W_diag | 2 => W_pole | _ => W_pp
def invof (i j : ℕ) : Kel := match clsIdx i j with | 0 => inv_adj | 1 => inv_diag | 2 => inv_pole | _ => inv_pp
def T6of (i j : ℕ) : T6 := match clsIdx i j with | 0 => T6adj | 1 => T6diag | 2 => T6pole | _ => T6pp
def Kof (i j : ℕ) : ℚ := match clsIdx i j with | 0 => K_adj | 1 => K_diag | 2 => K_pole | _ => K_pp
def clof (i j : ℕ) : Cls := match clsIdx i j with | 0 => cl_adj | 1 => cl_diag | 2 => cl_pole | _ => cl_pp
/-- `W_ij` with zero diagonal -/
def Wtab (i j : ℕ) : Kel := if i = j then Kel.zero else Wof i j
/-- `μᵢ`: 0 on the ring, −1/4 at the poles -/
def muk (i : ℕ) : Kel := if i < 5 then Kel.zero else Kel.ofQ (-1/4)

def dotK (u v : ℕ → Kel) : Kel := ((u 0).mul (v 0)).add (((u 1).mul (v 1)).add ((u 2).mul (v 2)))
/-- `e_c × P` -/
def crossK (c : ℕ) (P : ℕ → Kel) (k : ℕ) : Kel :=
  if c = 0 then (if k = 0 then Kel.zero else if k = 1 then Kel.zero.sub (P 2) else P 1)
  else if c = 1 then (if k = 0 then P 2 else if k = 1 then Kel.zero else Kel.zero.sub (P 0))
  else (if k = 0 then Kel.zero.sub (P 1) else if k = 1 then P 0 else Kel.zero)
def ksum (l : List Kel) : Kel := l.foldr Kel.add Kel.zero

/-! ### The six pair atoms as polynomials in `(x₁, x₂, x₃, x₄) = (x_{2i}, x_{2i+1}, x_{2j}, x_{2j+1})` -/

def atA (i j : ℕ) : Poly :=
  [([0, 0, 0, 1], dotK (Pk i) (E2k j)), ([0, 0, 1, 0], dotK (Pk i) (E1k j)),
   ([0, 1, 0, 0], dotK (E2k i) (Pk j)), ([1, 0, 0, 0], dotK (E1k i) (Pk j))]
def atB (i j : ℕ) : Poly :=
  [([0, 1, 0, 1], dotK (E2k i) (E2k j)), ([0, 1, 1, 0], dotK (E2k i) (E1k j)),
   ([1, 0, 0, 1], dotK (E1k i) (E2k j)), ([1, 0, 1, 0], dotK (E1k i) (E1k j))]
def atC (i j : ℕ) : Poly := [([0, 0, 0, 1], dotK (Pk i) (E2k j)), ([0, 0, 1, 0], dotK (Pk i) (E1k j))]
def atCp (i j : ℕ) : Poly := [([0, 1, 0, 0], dotK (E2k i) (Pk j)), ([1, 0, 0, 0], dotK (E1k i) (Pk j))]
def atRi : Poly := [([0, 2, 0, 0], Kel.ofQ 1), ([2, 0, 0, 0], Kel.ofQ 1)]
def atRj : Poly := [([0, 0, 0, 2], Kel.ofQ 1), ([0, 0, 2, 0], Kel.ofQ 1)]

/-! ### Exact K-identities (each one `decide +kernel`) -/

/-- orthonormal frames and completeness -/
def frameOK : Bool := (List.range 7).all fun i =>
  decide (dotK (Pk i) (Pk i) = Kel.ofQ 1) && decide (dotK (E1k i) (E1k i) = Kel.ofQ 1)
  && decide (dotK (E2k i) (E2k i) = Kel.ofQ 1) && decide (dotK (Pk i) (E1k i) = Kel.zero)
  && decide (dotK (Pk i) (E2k i) = Kel.zero) && decide (dotK (E1k i) (E2k i) = Kel.zero)
  && ((List.range 3).all fun k => (List.range 3).all fun l =>
      decide (((Pk i k).mul (Pk i l)).add (((E1k i k).mul (E1k i l)).add ((E2k i k).mul (E2k i l)))
        = Kel.ofQ (if k = l then 1 else 0)))
theorem frameOK_true : frameOK = true := by decide +kernel

/-- the rotation fields reconstruct `e_c × Pᵢ` -/
def rotOK : Bool := (List.range 7).all fun i => (List.range 3).all fun c => (List.range 3).all fun k =>
  decide (((Kd (2 * i) c).mul (E1k i k)).add ((Kd (2 * i + 1) c).mul (E2k i k)) = crossK c (Pk i) k)
theorem rotOK_true : rotOK = true := by decide +kernel

/-- Gram matrix of the kernel vectors -/
def gramOK : Bool := (List.range 5).all fun b => (List.range 5).all fun b' =>
  decide (ksum ((List.range 14).map fun p => (Kd p b).mul (Kd p b')) = Kel.ofQ (if b = b' then gram b else 0))
theorem gramOK_true : gramOK = true := by decide +kernel

/-- per pair: `⟪Pᵢ,Pⱼ⟫ = g`, `inv(1−g) = 1`, `2W = inv`, `g ≤ 0.31`, `1 − g² ≤ sg²`, `sg ≥ 0` -/
def pairOK : Bool := (List.range 7).all fun i => (List.range 7).all fun j =>
  if i = j then true else
  decide (dotK (Pk i) (Pk j) = gof i j) && decide ((invof i j).mul ((Kel.ofQ 1).sub (gof i j)) = Kel.ofQ 1)
  && decide ((Kel.ofQ 2).mul (Wof i j) = invof i j) && decide ((gof i j).hi aLo aHi ≤ 31/100)
  && (decide (((Kel.ofQ 1).sub ((gof i j).mul (gof i j))).hi aLo aHi ≤ (clof i j).bC ^ 2)
      && decide (0 ≤ (clof i j).bC))
theorem pairOK_true : pairOK = true := by decide +kernel

/-- criticality `Σ_{j≠i} W_ij Pⱼ = μᵢ Pᵢ` -/
def critOK : Bool := (List.range 7).all fun i => (List.range 3).all fun k =>
  decide (ksum ((List.range 7).map fun j => (Wtab i j).mul (Pk j k)) = (muk i).mul (Pk i k))
theorem critOK_true : critOK = true := by decide +kernel

def symOK : Bool := (List.range 7).all fun i => (List.range 7).all fun j => decide (Wtab i j = Wtab j i)
theorem symOK_true : symOK = true := by decide +kernel

def clsOK : Bool := (List.range 7).all fun i => (List.range 7).all fun j =>
  decide (clsIdx i j ≤ 4) && (decide (i = j) || decide (clsIdx i j < 4))
theorem clsOK_true : clsOK = true := by decide +kernel

lemma clsIdx_le {i j : ℕ} (hi : i < 7) (hj : j < 7) : clsIdx i j ≤ 4 := by
  have h := clsOK_true
  simp only [clsOK, List.all_eq_true, List.mem_range, Bool.and_eq_true, Bool.or_eq_true, decide_eq_true_eq] at h
  exact (h i hi j hj).1

lemma clsIdx_lt {i j : ℕ} (hi : i < 7) (hj : j < 7) (hij : i ≠ j) : clsIdx i j < 4 := by
  have h := clsOK_true
  simp only [clsOK, List.all_eq_true, List.mem_range, Bool.and_eq_true, Bool.or_eq_true, decide_eq_true_eq] at h
  exact (h i hi j hj).2.resolve_left hij

lemma Wtab_sym {i j : ℕ} (hi : i < 7) (hj : j < 7) : Wtab i j = Wtab j i := by
  have h := symOK_true
  simp only [symOK, List.all_eq_true, List.mem_range, decide_eq_true_eq] at h
  exact h i hi j hj

end LocalFrames
'''


def frames_block():
    tab = [[4] * 7 for _ in range(7)]
    for (i, j) in PAIRS:
        tab[i][j] = tab[j][i] = CLSN[JG['pairs'][f'{i},{j}']['cls']]
    data = (f'def Pdat : List (List Kel) :=\n  {kmat(JG["P"])}\ndef E1dat : List (List Kel) :=\n  {kmat(JG["E1"])}\n'
            f'def E2dat : List (List Kel) :=\n  {kmat(JG["E2"])}\n'
            f'/-- kernel vectors: row `p` = coordinate `p`, columns `r₁ r₂ r₃ ŝ₁ ŝ₂` -/\ndef Kdat : List (List Kel) :=\n  {kmat(JG["Kd"])}\n'
            f'def clsTab : List (List ℕ) := {tab}\n')
    return FRAMES_HEAD + data + FRAMES_TAIL


PAIRDATA_HEAD = '''import LogLean.LocalBomb

/-!
# LocalPairData: the 21 pair polynomials `p_ij = Σ_{d=2}^{6} p_ij,d` (generated data)

GENERATED by `lean/gen/export_local_data.py pairs` from `local_global.py` (data of `local_pre.py`); do not edit.
`pijd i j d` is the homogeneous degree-`d` part of the minorant of pair `(i,j)` in the 4 local coordinates
`(x_{2i}, x_{2i+1}, x_{2j}, x_{2j+1})`, coefficients in K = ℚ(α); `B5sq i j`, `B6sq i j` its Bombieri squares
(exact, in K) and `B5b i j`, `B6b i j` rational upper bounds of their square roots.
-/

namespace LocalPairData
open LocalKel LocalSP

'''

PAIRDATA_MID = '''/-- homogeneous part of degree `d` (2 ≤ d ≤ 6) of the pair polynomial -/
def pijd (i j d : ℕ) : Poly := ((pijTab.getD i []).getD j []).getD (d - 2) []
/-- the pair polynomial `p_ij` -/
def pij (i j : ℕ) : Poly :=
  merge (pijd i j 2) (merge (pijd i j 3) (merge (pijd i j 4) (merge (pijd i j 5) (pijd i j 6))))

'''

PAIRDATA_TAIL = '''def B5sq (i j : ℕ) : Kel := (B5sqTab.getD i []).getD j Kel.zero
def B6sq (i j : ℕ) : Kel := (B6sqTab.getD i []).getD j Kel.zero
def B5b (i j : ℕ) : ℚ := (B5Tab.getD i []).getD j 0
def B6b (i j : ℕ) : ℚ := (B6Tab.getD i []).getD j 0

end LocalPairData
'''


def pairdata_block():
    P = JG['pairs']
    out = [PAIRDATA_HEAD]
    for (i, j) in PAIRS:
        d = P[f'{i},{j}']
        for k in range(2, 7):
            out.append(f'def p{i}{j}_{k} : Poly :=\n  {poly_lean(d["parts"][str(k)])}\n')
        out.append('\n')
    tab = '[' + ',\n   '.join('[' + ', '.join(('[' + ', '.join(f'p{i}{j}_{k}' for k in range(2, 7)) + ']') if i < j else '[]'
                                              for j in range(7)) + ']' for i in range(7)) + ']'
    out.append(f'def pijTab : List (List (List Poly)) :=\n  {tab}\n')
    out.append(PAIRDATA_MID)

    def tabq(key):
        return '[' + ',\n   '.join('[' + ', '.join((q(P[f"{i},{j}"][key]) if i < j else '0') for j in range(7)) + ']'
                                   for i in range(7)) + ']'

    def tabk(key):
        return '[' + ',\n   '.join('[' + ', '.join((kel(P[f"{i},{j}"][key]) if i < j else kel([0, 0, 0, 0]))
                                                for j in range(7)) + ']' for i in range(7)) + ']'
    out.append(f'def B5sqTab : List (List Kel) :=\n  {tabk("B5sq")}\ndef B6sqTab : List (List Kel) :=\n  {tabk("B6sq")}\n')
    out.append(f'def B5Tab : List (List ℚ) :=\n  {tabq("B5")}\ndef B6Tab : List (List ℚ) :=\n  {tabq("B6")}\n')
    out.append(PAIRDATA_TAIL)
    return ''.join(out)


def pairfile_block(name, prs):
    out = [f'''import LogLean.LocalFrames
import LogLean.LocalPairData

/-!
# {name}: pair-level Taylor-link identities `T6_g(atoms_ij(x)) = p_ij(x)` (T1), pairs {prs}

GENERATED by `lean/gen/export_local_data.py pairs`; each identity is one `decide +kernel`
(`LocalSP.checkEq6`), turned into the real identity by `LocalSP.eq_of_checkEq6` in `LocalMain`.
-/

namespace LocalPairs
open LocalKel LocalSP LocalAtom LocalFrames LocalPairData

''']
    for (i, j) in prs:
        out.append(f'set_option profiler true in\ntheorem check{i}{j} : checkEq6 (T6of {i} {j}) (atA {i} {j}) (atB {i} {j}) '
                   f'(atC {i} {j}) (atCp {i} {j}) atRi atRj (pij {i} {j}) = true := by\n  decide +kernel\n\n')
    out.append('end LocalPairs\n\n' + ''.join(f'#print axioms LocalPairs.check{i}{j}\n' for (i, j) in prs))
    return ''.join(out)


GLOB_HEAD = '''import LogLean.LocalBomb
import LogLean.LocalCert
import LogLean.LocalGamma1

/-!
# LocalGlobData: the global Taylor data in 14 variables and its `(σ, w)` expansion in 16 variables (generated)

GENERATED by `lean/gen/export_local_data.py glob` from `local_global.py`; do not edit.
* `F2 F3 F4`: the degree 2, 3, 4 parts of the minorant `𝒫` in the 14 frame coordinates (`F4 = F4c0 ++ … ++ F4c3`);
* `poles2 poles4`: the pole point terms `r²/8`, `r⁴/32`;
* `G4c0 … G4c3`: `F4ck(σ₁ŝ₁ + σ₂ŝ₂ + w)` (variables `0,1 = σ`, `2..15 = w`); `Gd_k`: the σ-degree-`k` piece of
  `F_d(σ₁ŝ₁ + σ₂ŝ₂ + w)`;
* `D41 D42 D43t`: the σ-degree 1, 2, 3 pieces of `F4` as dense `w`-polynomials with coefficients in `(σ₁, σ₂)`
  (`D43t` = the gradient piece with its kernel component removed), `qb b` = `⟪k_b, ∇F₄(s)⟫/|k_b|²`.
Bombieri squares (exact): `‖F₃‖² = 5`, `‖F₄‖² = 35261/3840`, `‖D41‖² = c13|σ|²`, `‖D42‖² = c22|σ|⁴`,
`‖D43t‖² = c6|σ|⁶`.
-/

namespace LocalGlobData
open LocalKel LocalSP

'''


def glob_block():
    G = JG

    def dp_lean(ent):
        rows = [f'({wm}, {poly_lean(coef, ind="      ")})' for wm, coef, w in ent]
        return '[' + ',\n    '.join(rows) + ']'
    out = [GLOB_HEAD]
    out.append(f'def F2 : Poly :=\n  {poly_lean(G["F"]["2"])}\n\n')
    out.append(f'def F3 : Poly :=\n  {poly_lean(G["F"]["3"])}\n\n')
    for k, ch in enumerate(G['F4chunks']):
        out.append(f'def F4c{k} : Poly :=\n  {poly_lean(ch)}\n\n')
    out.append('/-- `F4` (the chunks are interleaved slices; the merge restores the sorted order) -/\ndef F4 : Poly := merge (merge F4c0 F4c1) (merge F4c2 F4c3)\n\n')
    out.append(f'def poles2 : Poly :=\n  {poly_lean(G["poles2"])}\n\ndef poles4 : Poly :=\n  {poly_lean(G["poles4"])}\n\n')
    for k, ch in enumerate(G['G4chunks']):
        out.append(f'def G4c{k} : Poly :=\n  {poly_lean(ch)}\n\n')
    for d in ('2', '3', '4'):
        for k, piece in G['Gp'][d].items():
            out.append(f'def G{d}_{k} : Poly :=\n  {poly_lean(piece)}\n\n')
    for nm, key in (('D41', 'F4s1'), ('D42', 'F4s2'), ('D43t', 'F4s3t')):
        out.append(f'def {nm} : LocalBomb.DP :=\n  {dp_lean(G["DP"][key])}\n\n')
    for b, qbp in enumerate(G['qb']):
        out.append(f'def qb{b} : Poly :=\n  {poly_lean(qbp)}\n')
    out.append('def qb (b : ℕ) : Poly := [qb0, qb1, qb2, qb3, qb4].getD b []\n\n')
    C = G['constants']
    consts = '\n'.join(f'def {nm} : ℚ := {q(C[key])}' for nm, key in
                       (('c13', 'c13'), ('c22', 'c22'), ('c6', 'c6'), ('G2b', 'G2'), ('C04', 'C04'), ('CQ22', 'CQ22'),
                        ('CQ13', 'CQ13'), ('CQ', 'CQ'), ('D1x4', 'D1x4'), ('B5pp', 'B5pp'), ('B6pp', 'B6pp')))
    out.append(consts + '\n\nend LocalGlobData\n')
    return ''.join(out)


if __name__ == '__main__':
    what = sys.argv[1:] or ['frames', 'pairs', 'glob']
    if 'frames' in what:
        open(os.path.join(LEAN, 'LocalFrames.lean'), 'w').write(frames_block()); print('wrote LocalFrames.lean')
    if 'pairs' in what:
        open(os.path.join(LEAN, 'LocalPairData.lean'), 'w').write(pairdata_block()); print('wrote LocalPairData.lean')
        for name, prs in (('LocalPairsA', PAIRS[:7]), ('LocalPairsB', PAIRS[7:14]), ('LocalPairsC', PAIRS[14:])):
            open(os.path.join(LEAN, name + '.lean'), 'w').write(pairfile_block(name, prs)); print('wrote', name)
    if 'glob' in what:
        open(os.path.join(LEAN, 'LocalGlobData.lean'), 'w').write(glob_block()); print('wrote LocalGlobData.lean')

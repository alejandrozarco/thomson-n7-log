def kel_al(c):
    return sum((R5(QQ(Fr(v).numerator, Fr(v).denominator)) * al ** k for k, v in enumerate(c)), R5(0))


def poly_al(p):
    out = R5(0)
    for m, c in p:
        term = kel_al(c)
        for k, e in enumerate(m):
            if e:
                term *= YS[k] ** e
        out += term
    return out


def lean_poly(p, vars_):
    """R5 element -> Lean expression text"""
    terms = []
    for m, c in sorted(p.items()):
        cq = Fr(int(c.numerator), int(c.denominator))
        mono = ' * '.join(f'{v} ^ {e}' if e > 1 else v for v, e in zip(vars_, m) if e)
        cs = f'({q(cq)})'
        terms.append(cs + (' * ' + mono if mono else ''))
    return ' + '.join(terms) if terms else '0'


